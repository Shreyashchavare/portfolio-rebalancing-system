BEGIN;

-- 1. Investor Profile Table
CREATE TABLE IF NOT EXISTS investor_profile (
    investor_id VARCHAR(20) PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    risk_category VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT check_risk_category_valid CHECK (risk_category IN ('LOW', 'MODERATE', 'HIGH'))
);

CREATE INDEX IF NOT EXISTS idx_investor_profile_risk_category ON investor_profile(risk_category);

-- 2. Portfolio Table
CREATE TABLE IF NOT EXISTS portfolio (
    portfolio_id VARCHAR(40) PRIMARY KEY,
    investor_id VARCHAR(20) NOT NULL REFERENCES investor_profile(investor_id),
    portfolio_name VARCHAR(255) NOT NULL,
    base_currency VARCHAR(10) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT check_portfolio_status_valid CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE INDEX IF NOT EXISTS idx_portfolio_investor_id ON portfolio(investor_id);
CREATE INDEX IF NOT EXISTS idx_portfolio_status ON portfolio(status);

-- 3. Instrument Catalog Table
CREATE TABLE IF NOT EXISTS instrument (
    instrument_id VARCHAR(20) PRIMARY KEY,
    symbol VARCHAR(20) NOT NULL,
    instrument_name VARCHAR(255) NOT NULL,
    asset_class VARCHAR(50) NOT NULL,
    lot_size NUMERIC(18, 4) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_instrument_symbol UNIQUE (symbol),
    CONSTRAINT check_lot_size_positive CHECK (lot_size > 0)
);

CREATE INDEX IF NOT EXISTS idx_instrument_symbol ON instrument(symbol);
CREATE INDEX IF NOT EXISTS idx_instrument_asset_class ON instrument(asset_class);
CREATE INDEX IF NOT EXISTS idx_instrument_is_active ON instrument(is_active);

-- 4. Holding Positions Table
CREATE TABLE IF NOT EXISTS holding (
    holding_id VARCHAR(100) PRIMARY KEY,
    portfolio_id VARCHAR(40) NOT NULL REFERENCES portfolio(portfolio_id),
    instrument_id VARCHAR(20) NOT NULL REFERENCES instrument(instrument_id),
    quantity NUMERIC(18, 4) NOT NULL,
    as_of_date DATE NOT NULL,
    CONSTRAINT check_holding_quantity_non_negative CHECK (quantity >= 0),
    CONSTRAINT uq_holding_portfolio_instrument_date UNIQUE (portfolio_id, instrument_id, as_of_date)
);

CREATE INDEX IF NOT EXISTS idx_holding_portfolio_id ON holding(portfolio_id);
CREATE INDEX IF NOT EXISTS idx_holding_instrument_id ON holding(instrument_id);
CREATE INDEX IF NOT EXISTS idx_holding_as_of_date ON holding(as_of_date);

-- 5. Market Price Table
CREATE TABLE IF NOT EXISTS market_price (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instrument_id VARCHAR(20) NOT NULL REFERENCES instrument(instrument_id),
    price NUMERIC(18, 4) NOT NULL,
    price_date DATE NOT NULL,
    source VARCHAR(100) NOT NULL,
    CONSTRAINT check_market_price_positive CHECK (price > 0),
    CONSTRAINT uq_market_price_instrument_date UNIQUE (instrument_id, price_date)
);

CREATE INDEX IF NOT EXISTS idx_market_price_instrument_id ON market_price(instrument_id);
CREATE INDEX IF NOT EXISTS idx_market_price_price_date ON market_price(price_date);

-- 6. Target Allocation Table
CREATE TABLE IF NOT EXISTS target_allocation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_id VARCHAR(40) NOT NULL REFERENCES portfolio(portfolio_id),
    asset_class VARCHAR(50) NOT NULL,
    target_weight NUMERIC(7, 4) NOT NULL,
    effective_from DATE NOT NULL,
    effective_to DATE,
    CONSTRAINT check_target_allocation_weight_range CHECK (target_weight >= 0 AND target_weight <= 100),
    CONSTRAINT check_target_allocation_effective_dates CHECK (effective_to IS NULL OR effective_to >= effective_from),
    CONSTRAINT uq_target_allocation_portfolio_asset_effective_from UNIQUE (portfolio_id, asset_class, effective_from)
);

CREATE INDEX IF NOT EXISTS idx_target_allocation_portfolio_id ON target_allocation(portfolio_id);
CREATE INDEX IF NOT EXISTS idx_target_allocation_asset_class ON target_allocation(asset_class);

-- 7. Fee Schedule Table
CREATE TABLE IF NOT EXISTS fee_schedule (
    fee_schedule_id VARCHAR(20) PRIMARY KEY,
    asset_class VARCHAR(50) NOT NULL,
    trade_side VARCHAR(4) NOT NULL,
    min_trade_value NUMERIC(18, 4) NOT NULL,
    max_trade_value NUMERIC(18, 4),
    fee_rate_bps NUMERIC(10, 4) NOT NULL,
    fixed_fee NUMERIC(18, 4) NOT NULL,
    minimum_fee NUMERIC(18, 4) NOT NULL,
    maximum_fee NUMERIC(18, 4),
    currency VARCHAR(3) NOT NULL,
    effective_from DATE NOT NULL,
    effective_to DATE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT check_fee_schedule_trade_value_range CHECK (min_trade_value >= 0 AND (max_trade_value IS NULL OR max_trade_value >= min_trade_value)),
    CONSTRAINT check_fee_schedule_fees_nonnegative CHECK (fee_rate_bps >= 0 AND fixed_fee >= 0 AND minimum_fee >= 0),
    CONSTRAINT check_fee_schedule_maximum_fee CHECK (maximum_fee IS NULL OR maximum_fee >= minimum_fee),
    CONSTRAINT check_fee_schedule_effective_dates CHECK (effective_to IS NULL OR effective_to >= effective_from),
    CONSTRAINT check_fee_schedule_trade_side_valid CHECK (trade_side IN ('BUY', 'SELL')),
    CONSTRAINT uq_fee_schedule_tier UNIQUE (asset_class, trade_side, min_trade_value, effective_from)
);

CREATE INDEX IF NOT EXISTS idx_fee_schedule_lookup ON fee_schedule(asset_class, trade_side, is_active);

-- 8. Policy & Risk Constraint Table (quoted reserved word "constraint")
CREATE TABLE IF NOT EXISTS "constraint" (
    constraint_id VARCHAR(30) PRIMARY KEY,
    constraint_name VARCHAR(100) NOT NULL,
    constraint_type VARCHAR(50) NOT NULL,
    scope_type VARCHAR(20) NOT NULL,
    scope_reference_id VARCHAR(50) NOT NULL,
    severity VARCHAR(10) NOT NULL,
    threshold_value NUMERIC(18, 4),
    threshold_unit VARCHAR(20),
    effective_from DATE NOT NULL,
    effective_to DATE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    description TEXT,
    CONSTRAINT check_constraint_scope_type_valid CHECK (scope_type IN ('PORTFOLIO', 'ASSET_CLASS', 'INSTRUMENT')),
    CONSTRAINT check_constraint_severity_valid CHECK (severity IN ('HARD', 'SOFT')),
    CONSTRAINT check_constraint_effective_dates CHECK (effective_to IS NULL OR effective_to >= effective_from),
    CONSTRAINT check_constraint_threshold_nonnegative CHECK (threshold_value IS NULL OR threshold_value >= 0),
    CONSTRAINT check_constraint_type_valid CHECK (constraint_type IN (
        'MAX_POSITION_WEIGHT', 'MIN_POSITION_WEIGHT', 'MIN_TRADE_VALUE',
        'MAX_TRADE_VALUE', 'MIN_TRADE_QUANTITY', 'MAX_TRADE_QUANTITY',
        'EXCLUDED_INSTRUMENT', 'LIQUIDITY_LIMIT'
    ))
);

CREATE INDEX IF NOT EXISTS idx_constraint_type ON "constraint"(constraint_type);
CREATE INDEX IF NOT EXISTS idx_constraint_scope ON "constraint"(scope_type, scope_reference_id);
CREATE INDEX IF NOT EXISTS idx_constraint_active_effective ON "constraint"(is_active, effective_from, effective_to);

-- 9. Constraint Instrument Bridge Table
CREATE TABLE IF NOT EXISTS constraint_instrument (
    constraint_id VARCHAR(30) NOT NULL REFERENCES "constraint"(constraint_id),
    instrument_id VARCHAR(20) NOT NULL REFERENCES instrument(instrument_id),
    PRIMARY KEY (constraint_id, instrument_id)
);

CREATE INDEX IF NOT EXISTS idx_constraint_instrument_instrument_id ON constraint_instrument(instrument_id);

-- 10. Rebalance Proposal Table
CREATE TABLE IF NOT EXISTS rebalance_proposal (
    proposal_id VARCHAR(30) PRIMARY KEY,
    portfolio_id VARCHAR(40) NOT NULL REFERENCES portfolio(portfolio_id),
    status VARCHAR(20) NOT NULL,
    review_decision VARCHAR(20) NOT NULL,
    pre_trade_portfolio_value NUMERIC(18, 4),
    post_trade_portfolio_value NUMERIC(18, 4),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_at TIMESTAMP WITH TIME ZONE,
    review_reason TEXT,
    CONSTRAINT check_rebalance_proposal_status_valid CHECK (status IN ('DRAFT', 'PENDING_REVIEW', 'APPROVED', 'REJECTED')),
    CONSTRAINT check_rebalance_proposal_review_decision_valid CHECK (review_decision IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT check_rebalance_proposal_pre_value_nonnegative CHECK (pre_trade_portfolio_value IS NULL OR pre_trade_portfolio_value >= 0),
    CONSTRAINT check_rebalance_proposal_post_value_nonnegative CHECK (post_trade_portfolio_value IS NULL OR post_trade_portfolio_value >= 0)
);

CREATE INDEX IF NOT EXISTS idx_rebalance_proposal_portfolio_id ON rebalance_proposal(portfolio_id);
CREATE INDEX IF NOT EXISTS idx_rebalance_proposal_status ON rebalance_proposal(status);
CREATE INDEX IF NOT EXISTS idx_rebalance_proposal_created_at ON rebalance_proposal(created_at);

-- 11. Trade Table
CREATE TABLE IF NOT EXISTS trade (
    trade_id VARCHAR(40) PRIMARY KEY,
    proposal_id VARCHAR(30) NOT NULL REFERENCES rebalance_proposal(proposal_id),
    instrument_id VARCHAR(20) NOT NULL REFERENCES instrument(instrument_id),
    fee_schedule_id VARCHAR(20) REFERENCES fee_schedule(fee_schedule_id),
    trade_side VARCHAR(4) NOT NULL,
    quantity NUMERIC(18, 4) NOT NULL,
    unit_price NUMERIC(18, 4) NOT NULL,
    trade_value NUMERIC(18, 4) NOT NULL,
    fee_amount NUMERIC(18, 4) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT check_trade_side_valid CHECK (trade_side IN ('BUY', 'SELL')),
    CONSTRAINT check_trade_status_valid CHECK (status IN ('PROPOSED', 'BLOCKED', 'APPROVED', 'REJECTED')),
    CONSTRAINT check_trade_quantity_positive CHECK (quantity > 0),
    CONSTRAINT check_trade_unit_price_positive CHECK (unit_price > 0),
    CONSTRAINT check_trade_value_positive CHECK (trade_value > 0),
    CONSTRAINT check_trade_fee_amount_nonnegative CHECK (fee_amount >= 0)
);

CREATE INDEX IF NOT EXISTS idx_trade_proposal_id ON trade(proposal_id);
CREATE INDEX IF NOT EXISTS idx_trade_instrument_id ON trade(instrument_id);
CREATE INDEX IF NOT EXISTS idx_trade_fee_schedule_id ON trade(fee_schedule_id);
CREATE INDEX IF NOT EXISTS idx_trade_status ON trade(status);

